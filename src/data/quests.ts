export type ObjectiveKind = 'kill' | 'killMiniboss' | 'killBoss' | 'clear' | 'reach' | 'bring' | 'deliver' | 'talk' | 'special';

export interface QuestObjective {
  kind: ObjectiveKind;
  /**
   * kill — enemy id (or 'any'); killMiniboss / killBoss / clear / reach — world node id;
   * bring — trophy id; deliver / talk — NPC id; special — a short id (the text explains).
   */
  target: string;
  count?: number;
  /** kill: only in this location. */
  where?: string;
  /** special: what to do; other kinds: an optional note. */
  text?: string;
}

export interface QuestReward {
  gold?: number;
  talentPoints?: number;
  lives?: number;
  runeStones?: number;
  item?: Rarity;
  gift?: 'common' | 'rare' | 'legendary';
  /** What opens (a service, a cheaper ride, new goods…). */
  unlock?: string;
}

export interface QuestDef {
  id: string;
  name: string;
  kind: QuestKind;
  giver: string;
  /** NPC to report to (default: the giver). */
  turnIn?: string;
  classId?: string;
  /** `flag`: something the hero has seen (a soul — ROADMAP 14.3). */
  requires?: { quests?: string[]; level?: number; flag?: 'soulSeen'; note?: string };
  /** What the giver says when offering the quest. */
  offer: string;
  objectives: QuestObjective[];
  /** What the turn-in NPC says at the end. */
  done: string;
  reward: QuestReward;
  /** The next quest of the chain. */
  next?: string;
  repeatable?: boolean;
}

